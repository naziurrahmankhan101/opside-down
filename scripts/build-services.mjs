/**
 * Generates services/<slug>.html from scripts/services-data.mjs.
 * The nav, mobile menu, footer and Lumi concierge are copied from index.html
 * (single source of truth) with their links rewritten to point back home.
 *
 *   node scripts/build-services.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { SERVICES } from './services-data.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const HOME = '../index.html';
const index = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8').replace(/\r\n/g, '\n');

const between = (start, end) => {
  const a = index.indexOf(start);
  const b = index.indexOf(end, a);
  if (a < 0 || b < 0) throw new Error(`index.html marker missing: ${start} … ${end}`);
  return index.slice(a, b);
};
// home-page anchors (#about, #faq, …) become links back to the home page
const homeLinks = (html) => html
  .replace(/href="#top"/g, `href="${HOME}"`)
  .replace(/href="#(?!main")([a-z-]+)"/g, `href="${HOME}#$1"`)
  .replace(/ data-scroll/g, '');

const NAV = homeLinks(between('<!-- ============ NAV ============ -->', '<main id="main">'))
  .replace('<header class="header is-over-hero" id="header">', '<header class="header" id="header">')
  .trimEnd();
const FOOTER = homeLinks(between('<!-- ============ FOOTER ============ -->', '<!-- ============ AI CONCIERGE ============ -->')).trimEnd();
const CONCIERGE = between('<!-- ============ AI CONCIERGE ============ -->', '<noscript>').trimEnd();

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const CHECK = '<svg viewBox="0 0 24 24" aria-hidden="true"><path d="M5 12.5l4.2 4.2L19 7"/></svg>';

function page(s) {
  const others = SERVICES.filter((o) => o.slug !== s.slug);
  return `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover" />
    <title>${esc(s.name)} — Opside Down</title>
    <meta name="description" content="${esc(s.meta)}" />
    <meta name="theme-color" content="#150e13" />
    <meta property="og:title" content="${esc(s.name)} — Opside Down" />
    <meta property="og:description" content="${esc(s.meta)}" />
    <meta property="og:type" content="website" />
    <link rel="icon" href="/favicon.svg" type="image/svg+xml" />
    <link rel="preload" as="image" href="/bg-gradient.webp" type="image/webp" />
    <!-- Critical CSS: dark from the first frame -->
    <style>html, body { margin: 0; background: #150e13; color: #f3eeec; } .skip-link { position: fixed; top: -80px; }</style>
  </head>
  <body class="page-service" data-home="${HOME}">
    <!-- generated by scripts/build-services.mjs — edit scripts/services-data.mjs, not this file -->
    <a class="skip-link" href="#main">Skip to content</a>
    <div class="scroll-progress" aria-hidden="true"><span id="scrollProgress"></span></div>

    ${NAV}

    <main id="main">
      <!-- ============ SERVICE HERO ============ -->
      <section class="section section--dark svc-hero" id="top">
        <div class="glow-orb glow-orb--a" aria-hidden="true"></div>
        <div class="container svc-hero__grid">
          <div class="svc-hero__copy">
            <nav class="svc-crumbs mono" aria-label="Breadcrumb" data-reveal>
              <a href="${HOME}#services">SERVICES</a><i aria-hidden="true">/</i><span aria-current="page">${s.num} · ${esc(s.short)}</span>
            </nav>
            <p class="eyebrow" data-reveal>// SERVICE ${s.num}</p>
            <h1 class="h2 svc-hero__title" data-split>${esc(s.h1[0])}<br /><span class="text-outline">${esc(s.h1[1])}</span></h1>
            <p class="svc-hero__sub" data-reveal>${esc(s.sub)}</p>
            <div class="svc-hero__ctas" data-reveal>
              <a href="${HOME}#contact" class="btn btn--paper btn--glow magnetic"><span>Book a free audit</span><b aria-hidden="true">↗</b></a>
              <a href="#how" data-scroll class="btn btn--ghost magnetic"><span>How it works</span></a>
            </div>
            <ul class="svc-facts mono" data-reveal>
              ${s.facts.map((f) => `<li><i class="live"></i>${esc(f)}</li>`).join('\n              ')}
            </ul>
          </div>
          <div class="card card--dark svc-hero__visual" data-card>
              ${s.mock}
              <p class="svc-hero__note mono">ILLUSTRATIVE PREVIEW</p>
          </div>
        </div>
      </section>

      <!-- ============ PROBLEM ============ -->
      <section class="section section--dark svc-problem">
        <div class="container">
          <div class="section__head">
            <div>
              <p class="eyebrow" data-reveal>// THE PROBLEM</p>
              <h2 class="h2" data-split>${esc(s.problem.h2[0])}<br /><span class="text-outline">${esc(s.problem.h2[1])}</span></h2>
            </div>
            <p class="section__lede" data-reveal>${esc(s.problem.lede)}</p>
          </div>
          <div class="svc-pains">
            ${s.problem.pains.map((p) => `<article class="card card--dark svc-pain" data-card data-glow>
              <span class="svc-pain__mark" aria-hidden="true"></span>
              <h3 class="h3">${esc(p.t)}</h3>
              <p>${esc(p.d)}</p>
            </article>`).join('\n            ')}
          </div>
        </div>
      </section>

      <!-- ============ HOW IT WORKS ============ -->
      <section class="section section--dark process svc-how" id="how">
        <div class="glow-orb glow-orb--b" aria-hidden="true"></div>
        <div class="container process__grid">
          <div class="process__head">
            <p class="eyebrow" data-reveal>// HOW IT WORKS</p>
            <h2 class="h2" data-split>HOW IT<br />WORKS.</h2>
            <p class="section__lede" data-reveal>Five steps that run quietly in the background while your team gets on with the day.</p>
            <div class="process__meter mono" aria-hidden="true">
              <span id="stepNow">01</span><i></i><span>${String(s.how.length).padStart(2, '0')}</span>
            </div>
          </div>
          <ol class="steps" id="steps">
            <li class="steps__rail" aria-hidden="true"><span id="stepsRail"></span></li>
            ${s.how.map((h, i) => {
              const n = String(i + 1).padStart(2, '0');
              return `<li class="step" data-step="${n}">
              <span class="step__num">${n}</span>
              <div class="step__body">
                <h3 class="h3">${esc(h.t)}</h3>
                <p>${esc(h.d)}</p>
                <ul class="step__list mono">${h.list.map((l) => `<li>▸ ${esc(l)}</li>`).join('')}</ul>
              </div>
            </li>`;
            }).join('\n            ')}
          </ol>
        </div>
      </section>

      <!-- ============ INCLUDED ============ -->
      <section class="section section--dark svc-included">
        <div class="container">
          <div class="section__head">
            <div>
              <p class="eyebrow" data-reveal>// WHAT'S INCLUDED</p>
              <h2 class="h2" data-split>EVERYTHING<br /><span class="text-outline">DONE FOR YOU.</span></h2>
            </div>
            <p class="section__lede" data-reveal>We build it, launch it and keep improving it. You own every part of it, fully documented.</p>
          </div>
          <ul class="svc-features">
            ${s.included.map((it) => `<li class="svc-feature" data-reveal>
              <span class="svc-feature__check">${CHECK}</span>
              <div><h3 class="svc-feature__t">${esc(it.t)}</h3><p>${esc(it.d)}</p></div>
            </li>`).join('\n            ')}
          </ul>
        </div>
      </section>

      <!-- ============ WHAT WE MEASURE ============ -->
      <section class="section section--dark svc-impact">
        <div class="container">
          <div class="section__head">
            <div>
              <p class="eyebrow" data-reveal>// WHAT WE MEASURE</p>
              <h2 class="h2" data-split>RESULTS YOU<br />CAN SEE.</h2>
            </div>
            <p class="section__lede" data-reveal>We agree the numbers that matter before we build, track them from day one and review them with you every month.</p>
          </div>
          <div class="svc-metrics">
            ${s.metrics.map((m, i) => `<article class="card card--dark svc-metric" data-card data-glow>
              <span class="svc-metric__k mono">KPI ${String(i + 1).padStart(2, '0')}</span>
              <h3 class="h3">${esc(m.t)}</h3>
              <p>${esc(m.d)}</p>
              <span class="svc-metric__bar" aria-hidden="true"><i style="--w:${[78, 64, 86, 58][i % 4]}%"></i></span>
            </article>`).join('\n            ')}
          </div>
        </div>
      </section>

      <!-- ============ BEST FOR ============ -->
      <section class="section section--dark svc-fit">
        <div class="container">
          <div class="section__head">
            <div>
              <p class="eyebrow" data-reveal>// BEST FOR</p>
              <h2 class="h2" data-split>BUILT FOR<br />BUSINESSES LIKE YOURS.</h2>
            </div>
            <p class="section__lede" data-reveal>Made for owners doing $30k–$150k a month in profit, with demand coming in and too much of it slipping away.</p>
          </div>
          <div class="svc-fits">
            ${s.fit.map((f) => `<article class="card card--dark svc-fitcard" data-card data-glow data-tilt>
              <span class="ind__tag mono">${esc(f.tag)}</span>
              <p>${esc(f.d)}</p>
            </article>`).join('\n            ')}
          </div>
        </div>
      </section>

      <!-- ============ FAQ ============ -->
      <section class="section section--dark faq" id="faq">
        <div class="container faq__grid">
          <div class="faq__head">
            <p class="eyebrow" data-reveal>// FAQ</p>
            <h2 class="h2" data-split>QUESTIONS,<br />ANSWERED.</h2>
            <p class="section__lede" data-reveal>Something else on your mind? <a href="${HOME}#contact" class="link">Ask us directly</a> — we reply within 24 hours.</p>
          </div>
          <div class="faq__list" id="faqList">
            ${s.faqs.map((f) => `<div class="faq__item" data-reveal>
              <button class="faq__q" aria-expanded="false"><span>${esc(f.q)}</span><i aria-hidden="true"></i></button>
              <div class="faq__a"><div><p>${esc(f.a)}</p></div></div>
            </div>`).join('\n            ')}
          </div>
        </div>
      </section>

      <!-- ============ CTA ============ -->
      <section class="section section--dark svc-cta">
        <div class="container svc-cta__inner">
          <p class="eyebrow" data-reveal>// NEXT STEP</p>
          <h2 class="h2 h2--xl" data-split>GROWTH STUCK?<br /><span class="text-outline">LET'S FLIP IT.</span></h2>
          <p class="section__lede" data-reveal>Book a free AI audit. In 30 minutes we'll show you where ${esc(s.name.toLowerCase())} would pay off first, with a written plan you keep.</p>
          <div class="svc-cta__btns" data-reveal>
            <a href="${HOME}#contact" class="btn btn--paper btn--glow magnetic"><span>Book my free audit</span><b aria-hidden="true">→</b></a>
            <a href="${HOME}#roi" class="btn btn--ghost magnetic"><span>Try the ROI calculator</span></a>
          </div>
        </div>
      </section>

      <!-- ============ MORE SERVICES ============ -->
      <section class="section section--dark svc-more">
        <div class="container">
          <div class="section__head">
            <div>
              <p class="eyebrow" data-reveal>// MORE SERVICES</p>
              <h2 class="h2" data-split>IT ALL<br />CONNECTS.</h2>
            </div>
            <p class="section__lede" data-reveal>Each system works on its own and gets stronger with the others. Most clients start with one.</p>
          </div>
          <div class="svc-more__grid">
            ${others.map((o) => `<a class="card card--dark svc-link" href="${o.slug}.html" data-card data-glow>
              <span class="svc-link__num mono">${o.num}</span>
              <h3 class="h3">${esc(o.short)}</h3>
              <span class="svc-link__go mono">EXPLORE <b aria-hidden="true">→</b></span>
            </a>`).join('\n            ')}
          </div>
        </div>
      </section>
    </main>

    ${FOOTER}

    ${CONCIERGE}

    <script type="module" src="/src/main.js"></script>
  </body>
</html>
`;
}

fs.mkdirSync(path.join(ROOT, 'services'), { recursive: true });
for (const s of SERVICES) {
  fs.writeFileSync(path.join(ROOT, 'services', `${s.slug}.html`), page(s));
}
console.log(`Generated ${SERVICES.length} service pages in services/`);
